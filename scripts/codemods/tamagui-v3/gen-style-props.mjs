#!/usr/bin/env node
/**
 * Regenerates `lib/style-props.data.mjs` from the Tamagui 3 style-prop tables.
 *
 *   node scripts/codemods/tamagui-v3/gen-style-props.mjs <@tamagui/helpers src dir>
 *
 * The directory is the extracted `@tamagui/helpers@3.x` `src/` folder. Its
 * sources are READ as text (never executed): every space-separated word inside
 * a `toObj('...')` string and every `key: true` entry of `cssStyleProps` is a
 * style prop. The output is checked in, so the codemod has no runtime
 * dependency on the extracted package.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = process.argv[2];
if (!dir) {
  console.error("usage: gen-style-props.mjs <@tamagui/helpers/src dir>");
  process.exit(2);
}

const files = ["validStyleProps.ts", "webOnlyStyleProps.ts", "cssStyleProps.ts"];
const props = new Set();
for (const file of files) {
  const text = fs.readFileSync(path.join(dir, file), "utf8");
  // words inside single-quoted strings (toObj sources)
  for (const m of text.matchAll(/'([A-Za-z][A-Za-z0-9 ]*)'/g)) {
    for (const word of m[1].split(/\s+/)) if (/^[A-Za-z]\w*$/.test(word)) props.add(word);
  }
  // `key: true,` object entries (cssStyleProps)
  for (const m of text.matchAll(/^\s+([A-Za-z]\w*): true,?$/gm)) props.add(m[1]);
}
// toObj(..., 'elevationAndroid') is an object literal in source
props.add("elevationAndroid");
for (const junk of ["web", "use", "strict"]) props.delete(junk);

const sorted = [...props].sort();
const out = `// GENERATED by gen-style-props.mjs from @tamagui/helpers 3.x validStyleProps.
// Do not edit by hand.
export const TAMAGUI_STYLE_PROPS = ${JSON.stringify(sorted, null, 0).replace(/","/g, '", "')};
`;
fs.writeFileSync(path.join(here, "lib", "style-props.data.mjs"), out);
console.log(`wrote ${sorted.length} style props`);
