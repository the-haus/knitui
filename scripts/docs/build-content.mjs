#!/usr/bin/env node
/**
 * build-content.mjs
 * -----------------
 * Indexes `apps/docs/content/**\/*.mdx` into a route table the app's catch-all
 * page can serve.
 *
 * Why a catch-all instead of file-based `page.mdx` files: Next's RSC pass treats
 * a compiled `.mdx` module as a client module, so `export const metadata` (the
 * documented way to title an MDX page) is rejected with "you are attempting to
 * export metadata from a component marked with use client". Routing through one
 * real `page.tsx` fixes that — metadata is produced by a server component from
 * each file's plain `export const meta`, and content files stay in a `content/`
 * tree instead of a deep nest of `app/**\/page.mdx` directories.
 *
 * Route mapping:
 *   content/docs/index.mdx                       -> /docs
 *   content/docs/getting-started/expo.mdx        -> /docs/getting-started/expo
 *   content/docs/components/inputs/button.mdx    -> /docs/components/inputs/button
 *
 * Writes: apps/docs/src/generated/content-map.ts
 *
 * Usage: node scripts/docs/build-content.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(SCRIPT_DIR, "..", "..");
const APP_DIR = join(REPO_ROOT, "apps/docs");
const CONTENT_DIR = join(APP_DIR, "content");
const OUT = join(APP_DIR, "src/generated/content-map.ts");

/** Every `.mdx` under content/, recursively. */
function walk(dir) {
  const out = [];
  for (const item of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, item.name);
    if (item.isDirectory()) out.push(...walk(full));
    else if (item.name.endsWith(".mdx")) out.push(full);
  }
  return out;
}

const files = walk(CONTENT_DIR).sort();

const routes = files.map((file) => {
  const rel = relative(CONTENT_DIR, file).split(sep).join("/");
  const withoutExtension = rel.replace(/\.mdx$/, "");
  const route = withoutExtension.replace(/\/index$/, "");
  // The import specifier is relative to src/generated/.
  const importPath = `../../content/${rel}`;
  // The title in the emitted comment is only a build-time aid for readers of the
  // generated file; real titles come from each module's `meta` export at render.
  const heading = /^#\s+(.+)$/m.exec(readFileSync(file, "utf8"))?.[1];
  return { route, importPath, heading };
});

const seen = new Set();
for (const { route } of routes) {
  if (seen.has(route)) throw new Error(`[content] duplicate route: /${route}`);
  seen.add(route);
}

const entries = routes
  .map(
    ({ route, importPath, heading }) =>
      `  ${JSON.stringify(route)}: () => import(${JSON.stringify(importPath)}),` +
      (heading ? ` // ${heading}` : ""),
  )
  .join("\n");

const module = `/* eslint-disable */
// GENERATED by scripts/docs/build-content.mjs — do not edit.
//
// route -> lazy import of that route's MDX module. The catch-all page
// (src/app/[[...slug]]/page.tsx) resolves a pathname through this map, reads the
// module's \`meta\` export for <title>/<meta description>, and renders its default
// export as the page body.
import type { ComponentType } from "react";

export type ContentMeta = {
  title?: string;
  description?: string;
  /** Set to keep a page out of the sitemap and the search index. */
  noindex?: boolean;
};

export type ContentModule = {
  default: ComponentType;
  meta?: ContentMeta;
};

export const contentModules: Record<string, () => Promise<ContentModule>> = {
${entries}
};

/** Every content route, without a leading slash. */
export const contentRoutes: string[] = Object.keys(contentModules);
`;

writeFileSync(OUT, module, "utf8");
console.log(`[content] ${routes.length} pages indexed`);
