#!/usr/bin/env node
// Freezes the kit's stock theme suite into `src/config/themes.generated.ts`.
//
// `src/config/themes.source.ts` holds the builder call (`@tamagui/config-v5/builder`
// `createThemes`). Running a builder at module scope cost every app start and
// every compiler pass; v3 recommends freezing the result instead. This script
// bundles the source with esbuild (so it needs no TS loader), runs it in node,
// and writes the resolved literal.
//
//   pnpm --filter @knitui/core generate:themes          # write
//   pnpm --filter @knitui/core generate:themes --check  # exit 1 if stale
//
// `themes.generated.test.ts` runs the same comparison under jest.
import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(here, "..");
const source = join(pkgRoot, "src/config/themes.source.ts");
const target = join(pkgRoot, "src/config/themes.generated.ts");

/** Serialize the themes object to a stable, prettier-compatible TS literal. */
export const renderThemesModule = (themes) => {
  const key = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));
  const lines = [
    "// GENERATED by `scripts/generate-themes.mjs` from `themes.source.ts`. DO NOT EDIT.",
    "// Regenerate with `pnpm --filter @knitui/core generate:themes`.",
    "",
    "export const themes = {",
  ];
  for (const name of Object.keys(themes)) {
    lines.push(`  ${key(name)}: {`);
    const theme = themes[name];
    for (const k of Object.keys(theme)) {
      lines.push(`    ${key(k)}: ${JSON.stringify(theme[k])},`);
    }
    lines.push("  },");
  }
  lines.push("} as const;", "");
  return lines.join("\n");
};

export const computeThemes = async () => {
  const dir = mkdtempSync(join(tmpdir(), "knitui-themes-"));
  try {
    const outfile = join(dir, "themes.mjs");
    await build({
      entryPoints: [source],
      outfile,
      bundle: true,
      format: "esm",
      platform: "node",
      logLevel: "error",
      // resolve the ESM builds of the @tamagui packages, as node would
      conditions: ["import", "default"],
    });
    const mod = await import(pathToFileURL(outfile).href);
    return mod.buildDefaultThemes();
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
};

const main = async () => {
  const check = process.argv.includes("--check");
  const next = renderThemesModule(await computeThemes());
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // first run: no generated file yet
  }
  if (check) {
    if (current !== next) {
      console.error(
        "themes.generated.ts is stale — run `pnpm --filter @knitui/core generate:themes`",
      );
      process.exit(1);
    }
    console.log("themes.generated.ts is up to date");
    return;
  }
  if (current !== next) writeFileSync(target, next);
  console.log(`wrote ${target}`);
};

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
